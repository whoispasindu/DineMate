$ErrorActionPreference = "Stop"

$Script:InfraDir = $PSScriptRoot
$Script:RepoDir = Split-Path -Parent $PSScriptRoot
$Script:EnvFile = Join-Path $PSScriptRoot ".env.business"
$Script:ComposeFile = Join-Path $PSScriptRoot "docker-compose.business.yml"
$Script:BackupDir = Join-Path $Script:RepoDir "backups"

function Write-Step([string]$Text) {
    Write-Host ""
    Write-Host "==> $Text" -ForegroundColor Cyan
}

function Stop-WithError([string]$Text) {
    Write-Host ""
    Write-Host $Text -ForegroundColor Red
    exit 1
}

function Assert-Docker {
    if (-not (Get-Command docker -ErrorAction SilentlyContinue)) {
        Stop-WithError "Docker Desktop is not installed. Install it from https://www.docker.com/products/docker-desktop/ and run this again."
    }
    docker info --format "{{.ServerVersion}}" *> $null
    if ($LASTEXITCODE -ne 0) {
        Stop-WithError "Docker Desktop is not running. Start it, wait until it says 'Engine running', and run this again."
    }
}

function New-Secret([int]$Bytes = 32) {
    $buffer = New-Object byte[] $Bytes
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try { $rng.GetBytes($buffer) } finally { $rng.Dispose() }
    return [Convert]::ToBase64String($buffer).TrimEnd("=").Replace("+", "-").Replace("/", "_")
}

function New-FernetKey {
    $buffer = New-Object byte[] 32
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try { $rng.GetBytes($buffer) } finally { $rng.Dispose() }
    return [Convert]::ToBase64String($buffer).Replace("+", "-").Replace("/", "_")
}

function Get-LanAddress {
    try {
        $candidates = Get-NetIPAddress -AddressFamily IPv4 -ErrorAction Stop |
            Where-Object {
                $_.IPAddress -notlike "127.*" -and
                $_.IPAddress -notlike "169.254.*" -and
                $_.InterfaceAlias -notmatch "vEthernet|WSL|Docker|Loopback|VirtualBox|VMware|Hyper-V"
            } |
            Sort-Object -Property @{ Expression = { if ($_.PrefixOrigin -eq "Dhcp") { 0 } else { 1 } } }, InterfaceMetric
        $first = $candidates | Select-Object -First 1
        if ($first) { return $first.IPAddress }
    } catch { }
    return "localhost"
}

function Read-EnvFile {
    $values = [ordered]@{}
    if (Test-Path $Script:EnvFile) {
        foreach ($line in Get-Content -Path $Script:EnvFile) {
            if ($line -match "^\s*([A-Z0-9_]+)=(.*)$") { $values[$Matches[1]] = $Matches[2] }
        }
    }
    return $values
}

function Write-EnvFile($Values) {
    $lines = @("# DineMate Business local server. Generated by install-business.ps1. Keep this file private.")
    foreach ($key in $Values.Keys) { $lines += "$key=$($Values[$key])" }
    [System.IO.File]::WriteAllLines($Script:EnvFile, [string[]]$lines, (New-Object System.Text.UTF8Encoding($false)))
}

function Get-ProfileArgs($Values) {
    $profiles = @()
    if ($Values.Contains("DINEMATE_PROFILES") -and $Values["DINEMATE_PROFILES"]) {
        foreach ($name in $Values["DINEMATE_PROFILES"].Split(",")) {
            if ($name.Trim()) { $profiles += @("--profile", $name.Trim()) }
        }
    }
    return $profiles
}

function Invoke-Compose([string[]]$Arguments) {
    $values = Read-EnvFile
    $all = @("compose", "--env-file", $Script:EnvFile, "-f", $Script:ComposeFile) + (Get-ProfileArgs $values) + $Arguments
    & docker @all
    if ($LASTEXITCODE -ne 0) { Stop-WithError "docker $($Arguments -join ' ') failed. See the messages above." }
}

function Update-StreamHost {
    $values = Read-EnvFile
    $address = Get-LanAddress
    if ($values["DINEMATE_STREAM_HOST"] -ne $address) {
        $values["DINEMATE_STREAM_HOST"] = $address
        Write-EnvFile $values
    }
    return $address
}

function Show-Urls([string]$Address) {
    $values = Read-EnvFile
    $port = if ($values["WEB_PORT"]) { $values["WEB_PORT"] } else { "8080" }
    Write-Host ""
    Write-Host "DineMate Business is running." -ForegroundColor Green
    Write-Host "  On this computer:            http://localhost:$port"
    if ($Address -ne "localhost") {
        Write-Host "  On phones and laptops here:  http://${Address}:$port  (same Wi-Fi)"
    }
}
